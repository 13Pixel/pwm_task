/**********************************************************************************************************************
 * Definitions of private functions
 *********************************************************************************************************************/
static void PWM_APP_Task(void *pvParameters) {
    while (true) {
        sUART_Cmd_handler_Commands_t message = {0};
        if (PWM_API_GetMessage(&message) == true) {
            if (message.command_enum == eUART_CMD_handler_Commands_SetPWM) {
                sPWM_API_Set_PWM_Command_t *data = (sPWM_API_Set_PWM_Command_t *) message.data;
                PWM_API_Start(data);
            }
        }
    }
}

/**********************************************************************************************************************
 * Definitions of exported functions
 *********************************************************************************************************************/
bool PWM_APP_Init() {
    PWM_API_Init();

    xTaskCreatePinnedToCore(PWM_APP_Task, TaskAttributes_pwm.name, 2048, NULL, TaskAttributes_pwm.uxPriority, NULL,
                            0);

    return true;
}