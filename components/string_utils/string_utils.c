bool remchar (char *string, const char *char_list) {
    if (string == NULL || char_list == NULL) {
        return false;
    }
    uint16_t bad_chars_count = 0;
    for (uint16_t i = 0; i <= strlen(string); i++) {
        if (bad_chars_count > 0) {
            string[i - bad_chars_count] = string[i];
        }
        for (uint16_t c = 0; c < strlen(char_list); c++) {
            if (string[i] == char_list[c]) {
                bad_chars_count++;
            }
        }
    }
    return true;
}

bool strToHexa(char *string, char *hexStr){
    if (string == NULL || hexStr == NULL) {
        return false;
    }
    int i, j = 0;
    for (i = 0; i < strlen(string); i++)
    {
        sprintf(hexStr + j, "%02X", string[i]);
        j += 2;
    }

    hexStr[j] = '\0';
    return true;
}
